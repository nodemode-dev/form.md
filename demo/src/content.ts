const MEDIA = "assets/media";

function fig(file: string, w: number, h: number, show: number, alt: string, caption: string): string {
  return `<figure class="media media--image"><div class="media__frame"><img src="${MEDIA}/${file}" alt="${alt}" width="${show}" height="${Math.round((show * h) / w)}"></div><figcaption>${caption}</figcaption></figure>`;
}

