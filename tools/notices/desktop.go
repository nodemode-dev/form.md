func procMacroOnly(targets []struct {
	Kind []string `json:"kind"`
}) bool {
	lib := false
	for _, t := range targets {
		for _, k := range t.Kind {
			switch k {
			case "proc-macro":
				lib = true
			case "lib", "rlib", "dylib", "cdylib", "staticlib":
				return false
			}
		}
	}
	return lib
}

func crateLicense(dir, name, spdx string, authors []string, apache string) string {
	for _, f := range crateLicenseFiles {
		if b, err := os.ReadFile(filepath.Join(dir, f)); err == nil && len(bytes.TrimSpace(b)) > 0 {
			return string(b)
		}
	}
	holder := "the " + name + " authors"
	if len(authors) > 0 {
		holder = strings.Join(authors, ", ")
	}
	switch {
	case strings.Contains(spdx, "MIT"):
		return "MIT License (the crate ships no license file; its Cargo.toml declares " + spdx + ")\n\nCopyright (c) " + holder + "\n\n" + mitBody
	case strings.Contains(spdx, "Apache-2.0"):
		return "Apache License 2.0 (the crate ships no license file; its Cargo.toml declares " + spdx + "; copyright " + holder + ")\n\n" + apache
	case strings.Contains(spdx, "BSD-3-Clause"):
		return "BSD 3-Clause License (the crate ships no license file; its Cargo.toml declares " + spdx + ")\n\nCopyright (c) " + holder + "\n\n" + bsd3Body
	case spdx == "MPL-2.0":
		return "Mozilla Public License 2.0, used unmodified. Source code: https://crates.io/crates/" + name + "\n\n" + mplText
	}
	fmt.Fprintf(os.Stderr, "notices: crate %s declares %q and ships no license file\n", name, spdx)
	os.Exit(1)
	return ""
}
