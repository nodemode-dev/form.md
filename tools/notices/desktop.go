var mplText string

var desktopTargets = []string{
	"aarch64-apple-darwin",
	"x86_64-apple-darwin",
	"x86_64-unknown-linux-gnu",
	"aarch64-unknown-linux-gnu",
	"x86_64-pc-windows-msvc",
}

var crateLicenseFiles = []string{"LICENSE-MIT", "LICENSE-MIT.txt", "LICENSE-MIT.md", "LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING", "LICENSE-APACHE", "LICENSE-APACHE.txt", "LICENSE-ZLIB", "LICENSE-BSD", "license-mit", "license"}

type cargoMeta struct {
	Packages []struct {
		ID           string   `json:"id"`
		Name         string   `json:"name"`
		Version      string   `json:"version"`
		License      string   `json:"license"`
		ManifestPath string   `json:"manifest_path"`
		Authors      []string `json:"authors"`
		Targets      []struct {
			Kind []string `json:"kind"`
		} `json:"targets"`
	} `json:"packages"`
	Resolve struct {
		Root  string `json:"root"`
		Nodes []struct {
			ID   string `json:"id"`
			Deps []struct {
				Pkg      string `json:"pkg"`
				DepKinds []struct {
					Kind *string `json:"kind"`
				} `json:"dep_kinds"`
			} `json:"deps"`
		} `json:"nodes"`
	} `json:"resolve"`
}

func desktopNotices(root string) {
	manifest := filepath.Join(root, "src-tauri", "Cargo.toml")
	apache, err := os.ReadFile(filepath.Join(root, "LICENSE"))
	check(err)
	type crate struct{ name, version, license, text string }
	found := map[string]crate{}
	for _, target := range desktopTargets {
		out, err := exec.Command("cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target, "--manifest-path", manifest).Output()
		check(err)
		var m cargoMeta
		check(json.Unmarshal(out, &m))
		deps := map[string][]string{}
		for _, n := range m.Resolve.Nodes {
			for _, d := range n.Deps {
				for _, k := range d.DepKinds {
					if k.Kind == nil {
						deps[n.ID] = append(deps[n.ID], d.Pkg)
						break
					}
				}
			}
		}
		shipped := map[string]bool{}
		stack := []string{m.Resolve.Root}
		for len(stack) > 0 {
			id := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			if shipped[id] {
				continue
			}
			shipped[id] = true
			stack = append(stack, deps[id]...)
		}
		for _, p := range m.Packages {
			if !shipped[p.ID] || p.ID == m.Resolve.Root || procMacroOnly(p.Targets) {
				continue
			}
			key := p.Name + " " + p.Version
			if _, ok := found[key]; ok {
				continue
			}
			found[key] = crate{p.Name, p.Version, p.License, crateLicense(filepath.Dir(p.ManifestPath), p.Name, p.License, p.Authors, string(apache))}
		}
	}
	keys := make([]string, 0, len(found))
	for k := range found {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	b.WriteString("# Third-party notices · desktop app\n\n")
	b.WriteString("The form.md desktop app (`src-tauri`) links the Rust crates below into its window program, on at least one of macOS, Linux and Windows. Each is under its own license, reproduced in full. Proc-macro crates, which run only while compiling, are left out. Generated by `go run ./tools/notices desktop`; do not edit by hand. The server inside the app is covered by `NOTICES.md`.\n\n")
	b.WriteString("| Crate | Version | License |\n| --- | --- | --- |\n")
	for _, k := range keys {
		c := found[k]
		fmt.Fprintf(&b, "| %s | %s | %s |\n", c.name, c.version, strings.ReplaceAll(c.license, "|", "or"))
	}
	for _, k := range keys {
		c := found[k]
		fmt.Fprintf(&b, "\n## %s %s\n\n```text\n%s\n```\n", c.name, c.version, strings.TrimSpace(c.text))
	}
	check(os.WriteFile(filepath.Join(root, "src-tauri", "NOTICES.md"), b.Bytes(), 0o644))
	fmt.Printf("src-tauri/NOTICES.md: %d crates\n", len(keys))
}

