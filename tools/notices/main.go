package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

type component struct {
	name    string
	version string
	license string
	text    string
}

var licenseFiles = []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "LICENSE-MIT.txt", "LICENCE", "COPYING", "license", "license.md"}

func main() {
	root, err := os.Getwd()
	check(err)

	var comps []component
	comps = append(comps, stdlib())
	comps = append(comps, goModules(root)...)
	comps = append(comps, webPackages(root)...)
	comps = append(comps, fonts(root)...)

	sort.SliceStable(comps[1:], func(i, j int) bool { return comps[1+i].name < comps[1+j].name })

	var b bytes.Buffer
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("form.md is licensed under Apache-2.0 (see `LICENSE`). The binary and the embedded web client include the components below, each under its own license, reproduced in full. Generated by `go run ./tools/notices`; do not edit by hand.\n\n")
	b.WriteString("| Component | Version | License |\n| --- | --- | --- |\n")
	for _, c := range comps {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", c.name, c.version, c.license)
	}
	for _, c := range comps {
		fmt.Fprintf(&b, "\n## %s %s\n\n```text\n%s\n```\n", c.name, c.version, strings.TrimSpace(c.text))
	}
	check(os.WriteFile(filepath.Join(root, "NOTICES.md"), b.Bytes(), 0o644))
	fmt.Printf("NOTICES.md: %d components\n", len(comps))
}

func stdlib() component {
	text, err := os.ReadFile(filepath.Join(runtime.GOROOT(), "LICENSE"))
	check(err)
	return component{name: "Go standard library", version: runtime.Version(), license: classify(string(text)), text: string(text)}
}

func goModules(root string) []component {
	out, err := exec.Command("go", "list", "-deps", "-f",
		"{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}",
		"./cmd/form-md").Output()
	check(err)
	seen := map[string]bool{}
	var comps []component
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		if line == "" || seen[line] {
			continue
		}
		seen[line] = true
		f := strings.Split(line, "\t")
		text := readLicense(f[2])
		comps = append(comps, component{name: f[0], version: f[1], license: classify(text), text: text})
	}
	return comps
}

func webPackages(root string) []component {
	web := filepath.Join(root, "web")
	raw, err := os.ReadFile(filepath.Join(web, "package.json"))
	if err != nil {
		return nil
	}
	var pkg struct {
		Dependencies map[string]string `json:"dependencies"`
	}
	check(json.Unmarshal(raw, &pkg))
	type entry struct{ name, dir string }
	entries := []entry{{"vite", filepath.Join(web, "node_modules", "vite")}}
	if lockRaw, err := os.ReadFile(filepath.Join(web, "package-lock.json")); err == nil {
		var lock struct {
			Packages map[string]struct {
				Dev bool `json:"dev"`
			} `json:"packages"`
		}
		check(json.Unmarshal(lockRaw, &lock))
		for path, p := range lock.Packages {
			i := strings.LastIndex(path, "node_modules/")
			if p.Dev || i < 0 {
				continue
			}
			entries = append(entries, entry{path[i+len("node_modules/"):], filepath.Join(web, filepath.FromSlash(path))})
		}
	} else {
		for n := range pkg.Dependencies {
			entries = append(entries, entry{n, filepath.Join(web, "node_modules", n)})
		}
	}
	var comps []component
	for _, e := range entries {
		n, dir := e.name, e.dir
		meta, err := os.ReadFile(filepath.Join(dir, "package.json"))
		if err != nil {
			fmt.Fprintf(os.Stderr, "notices: %s not installed; run web/oc_install first\n", n)
			os.Exit(1)
		}
		var m struct {
			Version string `json:"version"`
			License string `json:"license"`
		}
		check(json.Unmarshal(meta, &m))
		label := n
		if n == "vite" {
			label = "vite (runtime helpers in the client bundle)"
		}
		comps = append(comps, component{name: label, version: m.Version, license: m.License, text: readLicense(dir)})
	}
	return comps
}

var fontFiles = []struct{ name, version, file string }{
	{"Inter (font files from @fontsource-variable/inter)", "5.3.0", "Inter-OFL.txt"},
	{"JetBrains Mono (font files from @fontsource-variable/jetbrains-mono)", "5.3.0", "JetBrainsMono-OFL.txt"},
}

func fonts(root string) []component {
	var comps []component
	for _, f := range fontFiles {
		text, err := os.ReadFile(filepath.Join(root, "web", "src", "fonts", f.file))
		check(err)
		comps = append(comps, component{name: f.name, version: f.version, license: classify(string(text)), text: string(text)})
	}
	return comps
}

func readLicense(dir string) string {
	for _, f := range licenseFiles {
		if b, err := os.ReadFile(filepath.Join(dir, f)); err == nil {
			return string(b)
		}
	}
	fmt.Fprintf(os.Stderr, "notices: no license file in %s\n", dir)
	os.Exit(1)
	return ""
}

func classify(text string) string {
	switch {
	case strings.Contains(text, "SIL Open Font License, Version 1.1"):
		return "OFL-1.1"
	case strings.Contains(text, "Apache License") && strings.Contains(text, "Version 2.0"):
		return "Apache-2.0"
	case strings.Contains(text, "Permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(text, "Permission to use, copy, modify, and"):
		return "ISC"
	case strings.Contains(text, "Redistribution and use in source and binary forms") && strings.Contains(text, "Neither the name"):
		return "BSD-3-Clause"
	case strings.Contains(text, "Redistribution and use in source and binary forms"):
		return "BSD-2-Clause"
	}
	return "see text"
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}
