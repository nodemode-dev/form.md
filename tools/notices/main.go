func webLicense(dir, name, spdx string, author json.RawMessage) string {
	for _, f := range licenseFiles {
		if b, err := os.ReadFile(filepath.Join(dir, f)); err == nil {
			return string(b)
		}
	}
	if spdx != "MIT" {
		return readLicense(dir)
	}
	holder := "the " + name + " authors"
	var s string
	var o struct {
		Name string `json:"name"`
	}
	if json.Unmarshal(author, &s) == nil && s != "" {
		holder = s
	} else if json.Unmarshal(author, &o) == nil && o.Name != "" {
		holder = o.Name
	}
	return "MIT License (the package ships no license file; its package.json declares MIT)\n\nCopyright (c) " + holder + "\n\n" + mitBody
}

func classify(text string) string {
	switch {
	case strings.Contains(text, "SIL Open Font License, Version 1.1"):
		return "OFL-1.1"
	case strings.Contains(text, "Apache License") && strings.Contains(text, "Version 2.0"):
		return "Apache-2.0"
	case strings.Contains(text, "Permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(text, "Permission to use, copy, modify, and"):
		return "ISC"
	case strings.Contains(text, "Redistribution and use in source and binary forms") && strings.Contains(text, "Neither the name"):
		return "BSD-3-Clause"
	case strings.Contains(text, "Redistribution and use in source and binary forms"):
		return "BSD-2-Clause"
	}
	return "see text"
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}
